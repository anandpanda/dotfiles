#!/usr/bin/env bash
# Work or personal: modules list folders in contexts/{personal,work}; install collects them.

contexts_file() { echo "$(state_dir)/contexts"; }
contexts_include_file() { echo "$HOME/.local/state/git/contexts.inc"; }

_contexts_read() { # CONTEXT FILE -> context<TAB>folder per usable line
  local line
  while IFS= read -r line || [ -n "$line" ]; do
    line="${line%%#*}"
    line="${line#"${line%%[![:space:]]*}"}"
    line="${line%"${line##*[![:space:]]}"}"
    [ -n "$line" ] || continue
    case "$line" in
      \~) line="$HOME" ;;
      \~/*) line="$HOME/${line#\~/}" ;;
    esac
    [ "$line" = / ] || line="${line%/}"
    case "$line" in
      /*) printf '%s\t%s\n' "$1" "$line" ;;
      *) log_warn "contexts: skip '$line' in $2 (not an absolute folder)" ;;
    esac
  done <"$2"
}

# Unique context<TAB>folder lines from the profile's public modules and the overlay's
# modules, shortest folder first so a nested folder's later include wins in git.
contexts_collect() {
  local profile names m d dirs="" root
  profile="${DOTFILES_PROFILE:-$(recall profile || echo personal)}"
  names="$(profile_modules "$profile")" || return 1
  root="$(modules_root)"
  for m in $names; do
    dirs="$dirs$root/$m
"
  done
  for d in "$(overlay_dir)"/modules/*/; do
    [ -d "$d" ] && dirs="$dirs${d%/}
"
  done
  while IFS= read -r d; do
    if [ -z "$d" ] || [ ! -d "$d" ]; then continue; fi
    module_enabled_for_os "$d" || continue
    for m in personal work; do
      [ ! -f "$d/contexts/$m" ] || _contexts_read "$m" "$d/contexts/$m"
    done
  done <<<"$dirs" | awk -F'\t' '!seen[$0]++ { print length($2) "\t" $0 }' | sort -s -n -k1,1 | cut -f2-
}

contexts_render_include() { # stdin: collected lines
  local c d
  echo "# Generated by the git module install from the modules' contexts/ lists."
  while IFS=$'\t' read -r c d; do
    [ -n "$d" ] || continue
    # git resolves symlinks in ~ (macOS /var -> /private/var) but not in an absolute pattern.
    case "$d" in "$HOME" | "$HOME"/*) d="~${d#"$HOME"}" ;; esac
    printf '[includeIf "gitdir:%s/"]\n    path = ~/.config/git/identity.%s\n' "$d" "$c"
  done
}

_contexts_put() { # FILE CONTENT
  if [ -f "$1" ] && [ "$(cat "$1")" = "$2" ]; then
    echo "skip $1"
  elif [ "${DRY_RUN:-0}" = 1 ]; then
    echo "[dry] write $1"
  else
    mkdir -p "$(dirname "$1")"
    printf '%s\n' "$2" >"$1.tmp" && mv "$1.tmp" "$1"
    echo "wrote $1"
  fi
}

# Write the state list and the git include. A folder in both contexts is an error, not a guess.
contexts_write() { # LINES (from contexts_collect)
  local twice
  twice="$(printf '%s\n' "$1" | cut -f2 | sort | uniq -d | tr '\n' ' ')"
  if [ -n "$twice" ]; then
    log_fail "contexts: listed as both personal and work: $twice"
    return 1
  fi
  _contexts_put "$(contexts_file)" "$1"
  _contexts_put "$(contexts_include_file)" "$(printf '%s\n' "$1" | contexts_render_include)"
}
